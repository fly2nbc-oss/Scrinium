/// Month number from a German month name, also abbreviated or misread by OCR ("Mrz", "M?rz", "Maerz").
fn month_from_name(name: &str) -> Option<u32> {
    let n = normalize(name);
    if n.starts_with('m') && !n.starts_with("mai") {
        return Some(3);
    }
    let m = match &n[..n.len().min(3)] {
        "jan" => 1,
        "feb" => 2,
        "apr" => 4,
        "mai" => 5,
        "jun" => 6,
        "jul" => 7,
        "aug" => 8,
        "sep" => 9,
        "okt" => 10,
        "nov" => 11,
        "dez" => 12,
        _ => return None,
    };
    Some(m)
}
